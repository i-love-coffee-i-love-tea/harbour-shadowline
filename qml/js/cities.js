// Filter cities by search query (case-insensitive substring match)
function filterCities(query) {
    if (!query || query.length === 0) return presetCities;
    var q = query.toLowerCase();
    var result = [];
    for (var i = 0; i < presetCities.length; i++) {
        if (presetCities[i].name.toLowerCase().indexOf(q) >= 0) {
            result.push(presetCities[i]);
        }
    }
    return result;
}